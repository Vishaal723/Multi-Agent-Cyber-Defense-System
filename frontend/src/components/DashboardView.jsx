import React from 'react';
import { Activity, AlertTriangle, BrainCircuit, ShieldAlert, ShieldCheck } from 'lucide-react';

const display = (value, suffix = '') => value === null || value === undefined || value === ''
  ? 'No data available'
  : (suffix && typeof value === 'string' && value.endsWith(suffix) ? value : `${value}${suffix}`);

function MetricCard({ label, value, note, color }) {
  return <article className="glass-panel dashboard-metric" style={{ borderTop: `2px solid ${color}` }}>
    <span>{label}</span><strong>{value}</strong><small>{note}</small>
  </article>;
}

export default function DashboardView({ dashboardStats, dashboardError, telemetryData, onSelectTab, onOpenIncident }) {
  const stats = dashboardStats?.summary || {};
  const severity = dashboardStats?.severity_distribution || {};
  const traffic = telemetryData?.traffic_stats || dashboardStats?.current_traffic || {};
  const incidents = telemetryData?.recent_incidents || dashboardStats?.recent_incidents || [];
  const agents = telemetryData?.agents || [];
  const messages = telemetryData?.agent_messages || [];
  const severityLevels = [
    ['Critical', '#f87171'], ['High', '#fb923c'], ['Medium', '#facc15'], ['Low', '#60a5fa']
  ];
  const maxSeverity = Math.max(1, ...severityLevels.map(([name]) => Number(severity[name] || 0)));

  return <div className="dashboard-layout">
    <header className="dashboard-heading">
      <div><p className="eyebrow">SECURITY OPERATIONS</p><h1>Operations overview</h1>
        <p>Persisted security records and clearly identified simulated telemetry.</p></div>
      <span className="data-source">Local demo environment</span>
    </header>

    {dashboardError && <div role="alert" className="dashboard-error">Dashboard metrics unavailable: {dashboardError}</div>}

    <section className="dashboard-metrics" aria-label="Security metrics">
      <MetricCard label="Threat records" value={display(stats.total_threats_detected)} note="Persisted threat records" color="#60a5fa" />
      <MetricCard label="Active incidents" value={display(stats.active_incidents)} note="Current incident records" color="#f87171" />
      <MetricCard label="Autonomous mitigation" value={display(stats.autonomous_mitigation_rate, '%')} note="Recorded autonomous actions / threats" color="#34d399" />
      <MetricCard label="Firewall DROP/DENY rules · isolated devices" value={`${display(stats.blocked_firewall_ips)} · ${display(stats.isolated_devices)}`} note="Stored policy and device records" color="#a78bfa" />
    </section>

    <section className="dashboard-columns">
      <article className="glass-panel dashboard-panel">
        <div className="panel-heading"><div><ShieldAlert /><h2>Threat severity</h2></div><span>Persisted records</span></div>
        {dashboardStats ? <div className="severity-list">{severityLevels.map(([name, color]) => {
          const count = severity[name] ?? 0;
          return <div className="severity-row" key={name}><div><span>{name}</span><b>{count}</b></div>
            <div className="severity-track"><i style={{ width: `${(Number(count) / maxSeverity) * 100}%`, background: color }} /></div></div>;
        })}</div> : <p className="empty-state">No data available.</p>}
      </article>

      <article className="glass-panel dashboard-panel">
        <div className="panel-heading"><div><Activity /><h2>Network activity</h2></div><span className="demo-label">Simulated telemetry</span></div>
        <p className="panel-note">Traffic figures are generated by the local demo monitor and are not captured from a production network.</p>
        <div className="traffic-grid">
          <div><span>Packet rate</span><b>{display(traffic.packet_rate_pps, ' pps')}</b></div>
          <div><span>Bandwidth</span><b>{display(traffic.bandwidth_mbps, ' Mbps')}</b></div>
          <div><span>Connections</span><b>{display(traffic.active_connections)}</b></div>
          <div><span>Dropped packets</span><b>{display(traffic.dropped_packets)}</b></div>
        </div>
        {telemetryData?.live_packet && <p className="panel-note">Latest generated packet: {telemetryData.live_packet.source_ip} → {telemetryData.live_packet.destination_ip} ({telemetryData.live_packet.protocol})</p>}
      </article>
    </section>

    <section className="dashboard-columns">
      <article className="glass-panel dashboard-panel">
        <div className="panel-heading"><div><AlertTriangle /><h2>Recent incidents</h2></div><button className="btn-cyber-outline" onClick={() => onSelectTab('incidents')}>View incidents</button></div>
        {incidents.length ? <div className="dashboard-record-list">{incidents.slice(0, 5).map((incident) => <button className="dashboard-record" key={incident.incident_id} onClick={() => onOpenIncident(incident.incident_id)}>
          <span><b>{incident.title || incident.incident_id}</b><small>{incident.incident_id} · {incident.created_at || 'Timestamp unavailable'}</small></span><span>{incident.severity || 'Severity unavailable'} · {incident.status || 'Status unavailable'}</span>
        </button>)}</div> : <p className="empty-state">No incident records available.</p>}
      </article>

      <article className="glass-panel dashboard-panel">
        <div className="panel-heading"><div><BrainCircuit /><h2>Agent and event feed</h2></div><span>{telemetryData ? 'Demo telemetry' : 'Waiting for telemetry'}</span></div>
        {agents.length ? <div className="agent-list">{agents.map((agent) => <div key={agent.agent_id} className="agent-row"><ShieldCheck /><span>{agent.name}</span><small>{agent.type || 'Role unavailable'}</small></div>)}</div> : <p className="empty-state">No agent telemetry available.</p>}
        <h3 className="subheading">Recent agent messages</h3>
        {messages.length ? <ul className="message-list">{messages.slice(0, 4).map((message, index) => <li key={message.message_id || index}>{message.sender} → {message.recipient}: {message.type}</li>)}</ul> : <p className="empty-state">No agent messages available.</p>}
        <p className="panel-note">The demo feed reports agent metadata; it does not establish production health or uptime.</p>
      </article>
    </section>
  </div>;
}
